/**
 * 一括査定サービス。
 *
 * このサイトは各社の「公表している」1gあたりの単価を並べているが、
 * 公表していない社(掲載25社のうち5社)や、そもそも掲載していない店の金額は分からない。
 * 全部まとめて聞きたい人には、一括査定のほうが早い。
 *
 * 並びを歪めないための決まり:
 * ・買取店のランキングには混ぜない。順位は公表単価だけで決める
 * ・ランキングを出したあとに、別の選択肢として置く
 * ・広告であることを明示する
 * ・「ここが一番高い」とは書かない。当サイトは一括査定の結果を測っていない
 *
 * url が空のあいだは何も表示しない。提携が承認されてリンクが発行されたら入れる。
 */
export interface Aggregator {
  id: string;
  name: string;
  /** 運営会社。誰に送るのかを読む人が分かるようにする */
  operator: string;
  /** サービス側が公表している提携社数などの説明。盛らない */
  summary: string;
  /** アフィリエイトリンク。空なら非表示 */
  url: string;
}

/**
 * ウリドキは2026-09-25にA8.netで提携申請済み(審査中)。
 * 承認されてリンクが発行されたら url に入れると表示される。
 * それまでは何も出ない。使えないボタンを置いても読む人の役に立たない。
 */
/**
 * 載せないと決めたもの。
 *
 * ラクーダ(ブランド品らくらく一括査定): A8で提携完了済み、新規買取成立7,000円と
 * 条件は良い。それでも載せない。2026-09-25に laqu-da.com を確認したところ、
 * 扱いはバッグ・時計・ジュエリーの3カテゴリだけで、金・プラチナ・貴金属・地金の
 * 記載がどこにも無い。加えて同社は
 *   「ホームページ記載以外の商品の買取を行っておりません！！！
 *     買取可能ブランドを必ずご確認ください」
 * と告知している。よくある質問にも金・貴金属の取扱記載は無い。
 *
 * このサイトの計算機を使う人の多くは、ブランド品ではなく「K18のネックレス何g」を
 * 売ろうとしている。そこへブランド品限定のサービスを置けば、行った先で断られる。
 * 報酬が取れても、送った人が無駄足を踏むなら載せる理由にならない。
 *
 * なお「ラクーダは金・プラチナも扱う」と書いている比較サイトがあるが、
 * 同社自身の記載ではない。一次情報を見て判断している。
 */
export const AGGREGATORS: Aggregator[] = [
  {
    id: "uridoki",
    name: "ウリドキ",
    operator: "ウリドキ株式会社",
    summary: "金・貴金属を最大10社に一括で査定依頼できるサービスです。",
    url: "",
  },
];

/** 表示できる(リンクが発行済みの)一括査定サービス */
export function availableAggregators(): Aggregator[] {
  return AGGREGATORS.filter((a) => a.url.trim().length > 0);
}
